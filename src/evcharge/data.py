"""Measurement data: synthetic reference-cell tests and a loader for real data.

The repository ships with *synthetic* test data so that it runs out of the box
without downloads. The data are generated by a second-order (2-RC) reference
cell with measurement noise. The identification step then fits a simpler
first-order (1-RC) model to it, so the fit contains a real model-structure
error, just like fitting a 1-RC model to a real cell.

To use real laboratory data (e.g. CALCE or NASA cell tests) export them to CSV
with the columns `time_s, current_a, voltage_v` (current > 0 = discharge) and
load them with `load_measurement_csv`.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

from .ecm import TheveninModel, nmc_reference_ocv


@dataclass
class Measurement:
    name: str
    time_s: np.ndarray
    current_a: np.ndarray
    voltage_v: np.ndarray
    soc0: float

    def to_frame(self) -> pd.DataFrame:
        return pd.DataFrame(
            {"time_s": self.time_s, "current_a": self.current_a, "voltage_v": self.voltage_v}
        )


def reference_cell(capacity_ah: float = 3.0) -> TheveninModel:
    """2-RC 'truth' cell used to create the synthetic measurements."""
    return TheveninModel(
        capacity_ah=capacity_ah,
        r0=0.028,
        r_rc=(0.012, 0.010),
        c_rc=(1200.0, 25000.0),  # tau = 14.4 s and 250 s
        ocv=nmc_reference_ocv,
        name="reference 2-RC cell",
    )


def _measure(cell: TheveninModel, t, i, soc0, name, rng, noise_v=1.5e-3, noise_i=5e-3):
    sim = cell.simulate(t, i, soc0)
    v_meas = sim["voltage"] + rng.normal(0.0, noise_v, len(t))
    i_meas = i + rng.normal(0.0, noise_i, len(t))
    return Measurement(name, t, i_meas, v_meas, soc0)


def low_rate_discharge(cell: TheveninModel, rng, c_rate: float = 0.05) -> Measurement:
    """C/20 full discharge, used to estimate the OCV-SOC curve."""
    current = c_rate * cell.capacity_ah
    duration = 3600.0 / c_rate * 0.995
    t = np.arange(0.0, duration, 30.0)
    i = np.full_like(t, current)
    return _measure(cell, t, i, 1.0, "C/20 discharge", rng)


def pulse_test(cell: TheveninModel, rng) -> Measurement:
    """HPPC-like test: 1C discharge pulses with rest, from 95 % to 10 % SOC."""
    q = cell.capacity_ah
    segments = []
    soc_step_s = 0.1 * 3600.0  # 10 % SOC at 1C
    for _ in range(8):
        segments += [(30.0, 1.0 * q), (40.0, 0.0), (10.0, -0.75 * q), (40.0, 0.0),
                     (soc_step_s - 30.0, 1.0 * q), (900.0, 0.0)]
    dt = 1.0
    i = np.concatenate([np.full(int(d / dt), c) for d, c in segments])
    t = np.arange(len(i)) * dt
    return _measure(cell, t, i, 0.95, "pulse test", rng)


def dynamic_profile(cell: TheveninModel, rng, duration_s: float = 3600.0) -> Measurement:
    """Driving-like current profile (accelerations, cruising, regeneration).

    Built from random segments, scaled to an average of about 0.5C discharge.
    It is used only for validation, never for fitting.
    """
    q = cell.capacity_ah
    dt = 1.0
    i = []
    while len(i) * dt < duration_s:
        kind = rng.choice(["accel", "cruise", "regen", "stop"], p=[0.25, 0.4, 0.2, 0.15])
        n = int(rng.uniform(5, 60) / dt)
        if kind == "accel":
            level = rng.uniform(1.0, 2.5) * q
        elif kind == "cruise":
            level = rng.uniform(0.2, 0.8) * q
        elif kind == "regen":
            level = -rng.uniform(0.3, 1.2) * q
        else:
            level = 0.0
        i.extend([level] * n)
    i = np.asarray(i[: int(duration_s / dt)])
    t = np.arange(len(i)) * dt
    return _measure(cell, t, i, 0.90, "dynamic profile", rng)


def make_synthetic_dataset(seed: int = 7, capacity_ah: float = 3.0) -> dict[str, Measurement]:
    rng = np.random.default_rng(seed)
    cell = reference_cell(capacity_ah)
    return {
        "ocv": low_rate_discharge(cell, rng),
        "pulse": pulse_test(cell, rng),
        "dynamic": dynamic_profile(cell, rng),
    }


def save_dataset(dataset: dict[str, Measurement], folder: Path) -> None:
    folder.mkdir(parents=True, exist_ok=True)
    for key, m in dataset.items():
        m.to_frame().to_csv(folder / f"{key}.csv", index=False, float_format="%.5f")


def load_measurement_csv(path: Path | str, soc0: float, name: str | None = None) -> Measurement:
    """Load a measurement exported as CSV (time_s, current_a, voltage_v)."""
    df = pd.read_csv(path)
    missing = {"time_s", "current_a", "voltage_v"} - set(df.columns)
    if missing:
        raise ValueError(f"{path}: missing columns {sorted(missing)}")
    return Measurement(
        name or Path(path).stem,
        df["time_s"].to_numpy(float),
        df["current_a"].to_numpy(float),
        df["voltage_v"].to_numpy(float),
        soc0,
    )
